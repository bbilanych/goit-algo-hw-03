# Функція приймає один параметр: date — рядок, що представляє дату у форматі 'РРРР-ММ-ДД' (наприклад, '2020-10-09').
# Функція повертає ціле число, яке вказує на кількість днів від заданої дати до поточної. Якщо задана дата пізніша за поточну, результат має бути від'ємним.
# У розрахунках необхідно враховувати лише дні, ігноруючи час (години, хвилини, секунди).
# Для роботи з датами слід використовувати модуль datetime Python.

from datetime import datetime


def get_days_from_today(date):
    """
    Повертає кількість днів між сьогоднішньою датою та датою у форматі 'YYYY-MM-DD'.
    У разі некоректного формату вхідних даних не падає з помилкою, а повертає None.
    """
    try:
        today = datetime.today()
        return (today - datetime.strptime(date, "%Y-%m-%d")).days
    except (TypeError, ValueError):
        # Некоректний формат або тип даних — функція не падає
        return None

print(get_days_from_today("2021-10-09"))